#!/usr/bin/env python3
"""cut_clips.py - <comp>/data/cuts.json -> <comp>/assets/footage/<id>.mp4 (cropped capture @ grid.fps, segments sped /
concatenated, last frame held to the slot length) + <comp>/data/cuts.js (window.CUTS) + static <video> tags in index.html
between <!--FOOTAGE:BEGIN--> / <!--FOOTAGE:END--> (the engine moves each tag into its slot; the renderer sees static media).

STATUS: SMOKE-TESTED (27/09 ProfitBase cut_v3.py; generalised = source dir / crop size / crop_y default / fps / crf from
        project.json instead of literals. Re-run here on a synthetic testsrc capture, see scripts/README.md)

  python scripts/build/cut_clips.py --config project.json [--only e04,e05] [--jobs 3] [--no-render]

cuts.json: {"clips": {"<id>": {"take": "<capture file stem in paths.footage_dir>", "t_in": s, "t_out": s,
            "segs": [[src_in, src_out, speed, crop_y?], ...], "view": [x, y, w, h]}}}
  t_in/t_out = VIDEO seconds (grid time); segs = seconds of the take file; crop_y default build.crop_y_default (70 = the
  white debugger bar y 0-69; 0 for frames where the bar was missing).
"""
import argparse, json, pathlib, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from lib.config import read_config, utf8_stdout  # noqa: E402

utf8_stdout()
ROOT = SRC = None
FPS, CROP_W, CROP_H, CY0, CRF, EXT = 30, 1920, 1010, 70, 17, ".mkv"


def build(cid, c):
    dur = round(c["t_out"] - c["t_in"], 4)
    parts, labels = [], []
    for i, s in enumerate(c["segs"]):
        a, b, sp = s[0], s[1], s[2]
        cy = s[3] if len(s) > 3 else CY0
        parts.append(f"[0:v]trim=start={a}:end={b},setpts=(PTS-STARTPTS)/{sp},crop={CROP_W}:{CROP_H}:0:{cy},fps={FPS},format=yuv420p[s{i}]")
        labels.append(f"[s{i}]")
    fc = ";".join(parts) + ";" + "".join(labels) + f"concat=n={len(labels)}:v=1:a=0,tpad=stop_mode=clone:stop_duration=12[v]"
    out = ROOT / "assets" / "footage" / f"{cid}.mp4"
    cmd = ["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(SRC / (c["take"] + EXT)), "-filter_complex", fc, "-map", "[v]",
           "-t", f"{dur:.4f}", "-c:v", "libx264", "-preset", "fast", "-crf", str(CRF), "-g", "15", "-an", str(out)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        return f"{cid} FAIL {r.stderr[-300:]}"
    got = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(out)],
                               capture_output=True, text=True).stdout)
    natural = sum((s[1] - s[0]) / s[2] for s in c["segs"])
    return f"{cid} OK {c['take']} dur {got:.3f}/{dur:.3f} natural {natural:.2f} {'HOLD %.2f' % (dur - natural) if natural < dur else 'TRIM %.2f' % (natural - dur)}"


def main():
    global ROOT, SRC, FPS, CROP_W, CROP_H, CY0, CRF, EXT
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=None)
    ap.add_argument("--only", default="")
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--no-render", action="store_true")
    a = ap.parse_args()
    cfg = read_config(a.config or "project.json")
    ROOT, SRC = cfg.comp(), cfg.p("footage_dir")
    B = cfg.get("build", {})
    FPS = int(cfg.get2("grid.fps", 30))
    CROP_W, CROP_H = [int(v) for v in str(B.get("crop", "1920:1010")).split(":")[:2]]
    CY0, CRF, EXT = int(B.get("crop_y_default", 70)), int(B.get("crf", 17)), B.get("source_ext", ".mkv")
    C = json.loads((ROOT / "data" / "cuts.json").read_text(encoding="utf-8"))["clips"]
    (ROOT / "assets" / "footage").mkdir(parents=True, exist_ok=True)
    ids = [k for k in C if not a.only or k in a.only.split(",")]
    if not a.no_render:
        with ThreadPoolExecutor(a.jobs) as ex:
            for line in ex.map(lambda k: build(k, C[k]), ids):
                print(line)
    (ROOT / "data" / "cuts.js").write_text("/* generated by scripts/build/cut_clips.py - DO NOT EDIT */\nwindow.CUTS = " + json.dumps(C) + ";\n", encoding="utf-8")
    tags = "\n".join(f'      <video id="v-{k}" class="fv" data-slot="{k}" src="assets/footage/{k}.mp4" muted playsinline '
                     f'data-start="{c["t_in"]}" data-duration="{round(c["t_out"] - c["t_in"], 4)}" data-track-index="{20 + i}"></video>'
                     for i, (k, c) in enumerate(C.items()))
    idx = ROOT / "index.html"
    h = idx.read_text(encoding="utf-8")
    h, n = re.subn(r"<!--FOOTAGE:BEGIN-->.*?<!--FOOTAGE:END-->", "<!--FOOTAGE:BEGIN-->\n" + tags + "\n      <!--FOOTAGE:END-->", h, flags=re.S)
    if n != 1:
        raise SystemExit("FOOTAGE markers not found exactly once in index.html")
    idx.write_text(h, encoding="utf-8")
    print(f"cuts.js + {len(C)} <video> tags written")


if __name__ == "__main__":
    main()
