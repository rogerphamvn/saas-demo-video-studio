#!/usr/bin/env python3
"""make_captions_js.py - <vo_dir>/captions.json (t0 = 0 nominal) -> <comp>/data/captions.js shifted by grid.json t0.
window.CAPS = { groups: [[text, start, end, line], ...], words: [[text, start, end, line], ...] }  (seconds, video time)
Caption TEXT is copied verbatim from the groups. Rule (27/09): no group shows a single word alone -> merged into the previous
group of the same line (else the next), <= captions.max_words (4) words.

STATUS: SMOKE-TESTED (27/09 ProfitBase; generalised = paths from project.json, max words from config. Re-run here on
        align.py --asr none output, see scripts/README.md)

  python scripts/build/make_captions_js.py --config project.json
"""
import json, pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from lib.config import load_config  # noqa: E402

cfg, _ = load_config(description=__doc__)
ROOT = cfg.comp()
MAXW = int(cfg.get2("captions.max_words", 4))
G = json.loads((ROOT / "data" / "grid.json").read_text(encoding="utf-8"))
C = json.loads((cfg.p("vo_dir") / "captions.json").read_text(encoding="utf-8"))
t0 = G["t0"]
line_of = {}
groups = []
for g in C["groups"]:
    for i in g["wordIdx"]:
        line_of[i] = g["line"]
    groups.append([g["text"], round(g["startMs"] / 1000 + t0, 4), round(g["endMs"] / 1000 + t0, 4), g["line"]])
# main 27/09: no group may show a single word alone -> merge into the previous group of the same line (else the next), <= 4 words
def nw(t): return len([x for x in t.split() if x not in ("—", "-", "–")])
i = 0
while i < len(groups):
    if nw(groups[i][0]) < 2:
        prv = i - 1 if i > 0 and groups[i - 1][3] == groups[i][3] and nw(groups[i - 1][0]) + 1 <= MAXW else None
        nxt = i + 1 if i + 1 < len(groups) and groups[i + 1][3] == groups[i][3] else None
        j = prv if prv is not None and (nxt is None or nw(groups[nxt][0]) >= nw(groups[prv][0])) else nxt
        if j is None and prv is not None: j = prv
        if j is not None:
            a, b = (j, i) if j < i else (i, j)
            groups[a] = [groups[a][0] + " " + groups[b][0], groups[a][1], groups[b][2], groups[a][3]]
            del groups[b]
            i = max(a - 1, 0)
            continue
    i += 1
words = [[w["text"].strip(), round(w["startMs"] / 1000 + t0, 4), round(w["endMs"] / 1000 + t0, 4), line_of.get(i, "")]
         for i, w in enumerate(C["captions"])]
out = {"t0": t0, "source": "captions.json", "groups": groups, "words": words}
(ROOT / "data" / "captions.js").write_text("/* generated by scripts/make_captions_js.py - DO NOT EDIT */\nwindow.CAPS = "
                                          + json.dumps(out, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"single-word groups left: {sum(1 for g in groups if nw(g[0]) < 2)} · max words {max(nw(g[0]) for g in groups)}")
print(f"captions.js: {len(groups)} groups, {len(words)} words, shifted +{t0}s")
